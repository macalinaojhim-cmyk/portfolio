/**
 * Safe localStorage wrapper — never throws,
 * even in sandboxed previews where storage is blocked.
 */
export const store = {
  get(key) {
    try {
      return window.localStorage.getItem(key);
    } catch {
      return null;
    }
  },
  set(key, value) {
    try {
      window.localStorage.setItem(key, value);
    } catch {
      /* ignore */
    }
  },
};
